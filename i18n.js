var I18N_LANG = 'ru';

function t(key, vars) {
  let s = I18N[I18N_LANG][key];
  if (s === undefined) s = I18N.ru[key];
  if (s === undefined) return key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(String(vars[k]));
  return s;
}

function applyI18n(root) {
  root = root || document;
  root.querySelectorAll('[data-i18n]').forEach(function (el) { el.textContent = t(el.getAttribute('data-i18n')); });
  root.querySelectorAll('[data-i18n-ph]').forEach(function (el) { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph'))); });
  root.querySelectorAll('[data-i18n-title]').forEach(function (el) { el.setAttribute('title', t(el.getAttribute('data-i18n-title'))); });
  root.querySelectorAll('[data-i18n-aria]').forEach(function (el) { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))); });
  root.querySelectorAll('[data-i18n-alt]').forEach(function (el) { el.setAttribute('alt', t(el.getAttribute('data-i18n-alt'))); });
  if (root === document) document.title = t('page_title');
}

function loadLang() {
  return new Promise(function (resolve) {
    chrome.storage.local.get(['blattam-lang'], function (result) {
      I18N_LANG = (result['blattam-lang'] === 'en') ? 'en' : 'ru';
      document.documentElement.lang = I18N_LANG;
      applyI18n();
      resolve(I18N_LANG);
    });
  });
}

function setLang(lang) {
  I18N_LANG = (lang === 'en') ? 'en' : 'ru';
  document.documentElement.lang = I18N_LANG;
  chrome.storage.local.set({ 'blattam-lang': I18N_LANG });
}
